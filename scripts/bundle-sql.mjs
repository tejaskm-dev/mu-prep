// Concatenates migrations + seed into supabase/setup.sql for one-paste setup in the SQL editor.
import fs from "node:fs";
import path from "node:path";

const root = path.join(process.cwd(), "supabase");
const migrations = fs
  .readdirSync(path.join(root, "migrations"))
  .filter((f) => f.endsWith(".sql"))
  .sort()
  .map((f) => `-- >>> migrations/${f}\n${fs.readFileSync(path.join(root, "migrations", f), "utf8")}`);
const seed = `-- >>> seed.sql\n${fs.readFileSync(path.join(root, "seed.sql"), "utf8")}`;
const header = `-- µPrep — complete database setup (generated by scripts/bundle-sql.mjs; edit the source files instead).
-- Paste this whole file into Supabase → SQL Editor → Run. Run it once on a fresh project.\n\n`;
fs.writeFileSync(path.join(root, "setup.sql"), header + [...migrations, seed].join("\n\n"));
console.log("Wrote supabase/setup.sql");
